# pkcs7_pad: hacer padding de los estados (añadir para completar 16)
def pkcs7_pad(data):
    pad_len = 16 - (len(data) % 16)
    return data + bytes([pad_len] * pad_len)

# hexXOR: hacer XOR para 2 números hexadecimales
def hexXOR(hex_str1, hex_str2):
  temp_value = int(hex_str1, 16) ^ int(hex_str2, 16) # convertir a decimal
  return format(temp_value, 'x') # regresar a hexadecimal

# matrixXOR: aplicar la función previa para todo un arreglo
def matrixXOR(state_matrix, round_key):
  new_state = []
  for i in range(len(state_matrix)):
    new_state.append(hexXOR(state_matrix[i], round_key[i]))
  return(new_state)

# subBytes: proceso de subBytes con ayuda de la matriz de sbox definida previamente
def subBytes(state):
  for i in range(len(state)):
    state[i] = int(state[i], 16) # convertir a decimal
  for i in range(len(state)):
    state[i] = sbox[state[i]] # encontrar en matriz sbox
  new_state = []
  for i in range(len(state)):
    new_state.append(format(state[i], 'x')) # regresar a hexadecimal

  return new_state

# shiftRows: proceso de shiftRows
def shiftRows(estado):
    nuevo_estado = estado.copy()

    for fila in range(4):
        fila_actual = []

        # sacar la fila desde el arreglo
        for columna in range(4):
            posicion = fila + columna * 4
            fila_actual.append(estado[posicion])

        # mover la fila a la izquierda según su número
        # fila 0 no se mueve
        # fila 1 se mueve 1 lugar
        # fila 2 se mueve 2 lugares
        # fila 3 se mueve 3 lugares
        fila_movida = fila_actual[fila:] + fila_actual[:fila]

        # regresar la fila movida al arreglo original
        for columna in range(4):
            posicion = fila + columna * 4
            nuevo_estado[posicion] = fila_movida[columna]

    return nuevo_estado

# mixColumns: proceso de MixColumns
def mixColumns(M):
  N = [None] * 16
  for i in range(16):
    if i % 4 == 0:
      a0=int(M[i], 16)
      a1=int(M[i+1], 16)
      a2=int(M[i+2], 16)
      a3=int(M[i+3], 16)

      N[i]= format(M2[a0] ^ M3[a1] ^ a2 ^ a3, 'x')
      N[i+1]= format(M2[a1] ^ M3[a2] ^ a0 ^ a3, 'x')
      N[i+2]= format(M2[a2] ^ M3[a3] ^ a0 ^ a1, 'x')
      N[i+3]= format(M2[a3] ^ M3[a0] ^ a1 ^ a2, 'x')

  return(N)

