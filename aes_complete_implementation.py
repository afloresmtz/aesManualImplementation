# inverseShiftRows: proceso de shiftRows inverso para desencriptación
def inverseShiftRows(estado):
    nuevo_estado = estado.copy()

    for fila in range(4):
        fila_actual = []

        # saco la fila desde el arreglo
        for columna in range(4):
            posicion = fila + columna * 4
            fila_actual.append(estado[posicion])

        # para desencriptar se mueve a la derecha
        # fila 0 no se mueve
        # fila 1 se mueve 1 lugar a la derecha
        # fila 2 se mueve 2 lugares a la derecha
        # fila 3 se mueve 3 lugares a la derecha
        if fila == 0:
            fila_movida = fila_actual
        else:
            fila_movida = fila_actual[-fila:] + fila_actual[:-fila]

        # regreso la fila movida al arreglo
        for columna in range(4):
            posicion = fila + columna * 4
            nuevo_estado[posicion] = fila_movida[columna]

    return nuevo_estado

# keyExpansion: en base a la llave inicial y a la matriz rcon, obtiene todas las llaves que se utilizarán
def keyExpansion(key, expanded_key):
  rcon = [["01", "00", "00", "00"],
          ["02", "00", "00", "00"],
          ["04", "00", "00", "00"],
          ["08", "00", "00", "00"],
          ["10", "00", "00", "00"],
          ["20", "00", "00", "00"],
          ["40", "00", "00", "00"],
          ["80", "00", "00", "00"],
          ["1b", "00", "00", "00"],
          ["36", "00", "00", "00"]]

  for i in range(16):
    expanded_key[i] = key[i]
  for i in range(176):
    if (i % 16 == 0) and (i != 0):
      # take last column
      temp = [expanded_key[i-4], expanded_key[i-3], expanded_key[i-2], expanded_key[i-1]]

      # rot word (only 1st one)
      temp_value = temp[0]
      temp.pop(0)
      temp.append(temp_value)

      # do sub bytes to every one
      temp = subBytes(temp)

      # xor with column 4 spaces earlier + rcon
      for j in range(4):
        expanded_key[i + j] = hexXOR(hexXOR(temp[j], rcon[(int(i / 16)) - 1][j]), expanded_key[i - 16 + j])
    elif (i > 16) and (i % 16 != 0 and i % 16 != 1 and i % 16 != 2 and i % 16 != 3):
      expanded_key[i] = hexXOR(expanded_key[i - 4], expanded_key[i - 16])
    else:
      continue
  return(expanded_key)

